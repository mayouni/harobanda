#!/bin/bash
# front_outside.sh -- the front proven outside the floor first (FRONT-1, as SRV-2 did for the server).
#
# Caddy, the proxy that terminates TLS (STZ-OS-RULING-18), run here as an UNPRIVILEGED user on a port
# above 1024 with a root the scene made and gave it, and asked by `harb get --tls` with nothing to trust
# but that root's PEM. Three questions:
#
#   1. over TLS, for the name the certificate carries: a 200, the TLS version, the root's fingerprint
#   2. over TLS, for a name the certificate does NOT carry: the handshake is refused by the client
#   3. in plain HTTP on the TLS port: Caddy answers 400 -- a front that ends TLS does not speak plain
#
# This host is not the machine's image, so it shows the program and the client, not the confinement;
# the boot of machines/qemu_front.machine (experiment/os11_front.sh) shows the rest.
#
#   wsl -d Ubuntu -- bash /mnt/d/GitHub/harobanda/experiment/front_outside.sh
#
# Needs Caddy fetched (experiment/caddy_fetch.sh) and the cross build. Log: zig-out/wsl/front_outside.txt
set -u
cd "$(dirname "$0")/.." || exit 1
H=zig-out/cross/x86_64-linux-musl/harb
C=zig-out/caddy/caddy
LOG=zig-out/wsl/front_outside.txt
W=/srv/harb-front-outside   # not under /root ('nobody' must traverse it), not under /tmp (cleared when the distro restarts)
mkdir -p zig-out/wsl
rm -f "$LOG"
(
  [ -x "$H" ] || { echo "no cross-built harb at $H (zig build cross)"; echo "exit 1"; exit 1; }
  [ -x "$C" ] || { echo "no caddy at $C (experiment/caddy_fetch.sh)"; echo "exit 1"; exit 1; }
  id nobody > /dev/null 2>&1 || { echo "no user 'nobody' here"; echo "exit 1"; exit 1; }
  rm -rf "$W"; mkdir -p "$W/storage"
  cp "$C" "$W/caddy"; cp "$H" "$W/harb"
  echo "=== the root, made here and given to the front (never generated by the floor) ==="
  openssl ecparam -genkey -name prime256v1 -noout -out "$W/root.key" 2> /dev/null
  openssl req -x509 -new -key "$W/root.key" -days 3650 -subj "/CN=Harobanda front, outside" -out "$W/root.crt" 2> /dev/null
  openssl x509 -in "$W/root.crt" -noout -subject -dates | sed 's/^/  /'
  echo "  fingerprint (sha256 of the DER, first 16 hex): $(openssl x509 -in "$W/root.crt" -outform DER | sha256sum | cut -c1-16)"
  cat > "$W/Caddyfile" <<'CF'
{
	admin off
	skip_install_trust
	auto_https disable_redirects
	storage file_system {
		root STORAGE
	}
	log {
		output file CADDYLOG
	}
	pki {
		ca local {
			name "Harobanda front, outside"
			root {
				cert ROOTCRT
				key ROOTKEY
			}
		}
	}
}

https://front.local:18443 {
	tls internal
	respond /health 200
}
CF
  sed -i -e "s|STORAGE|$W/storage|" -e "s|CADDYLOG|$W/caddy.log|" -e "s|ROOTCRT|$W/root.crt|" -e "s|ROOTKEY|$W/root.key|" "$W/Caddyfile"
  chown -R nobody "$W"
  echo "=== caddy, as nobody, on 18443 ==="
  # validated AS nobody: a validation provisions the CA into the storage, and one run as root left
  # files there that the unprivileged run could not open (the first run of this probe, 2026-10-19)
  runuser -u nobody -- "$W/caddy" validate --config "$W/Caddyfile" --adapter caddyfile > "$W/validate.txt" 2>&1 || { echo "the Caddyfile is refused:"; cat "$W/validate.txt"; echo "exit 1"; exit 1; }
  runuser -u nobody -- "$W/caddy" run --config "$W/Caddyfile" --adapter caddyfile > "$W/caddy.out" 2>&1 &
  CPID=$!
  up=no
  for i in $(seq 1 40); do
    sleep 0.25
    if ss -ltn 2>/dev/null | grep -q ':18443 '; then up=yes; break; fi
  done
  if [ "$up" != yes ]; then
    echo "caddy did not listen on 18443 within 10 s. Its console:"; tail -20 "$W/caddy.out" | cut -c1-300
    echo "Its own log:"; tail -20 "$W/caddy.log" 2>/dev/null | cut -c1-700
    kill $CPID 2>/dev/null; echo "exit 1"; exit 1
  fi
  CADDY_PID=$(pgrep -u nobody -x caddy | head -1)
  echo "caddy listens on 18443 (pid ${CADDY_PID:-?}, uid $(ps -o uid= -p "${CADDY_PID:-0}" 2>/dev/null | tr -d ' '))"
  verdict=0
  echo "=== 1. over TLS, for the name the certificate carries ==="
  L1=$("$W/harb" get 127.0.0.1 18443 /health --tls --ca "$W/root.crt" --name front.local); echo "$L1"
  echo "$L1" | grep -q -- '-- 200 over TLS 1.3; the certificate is for front.local, signed under the root fingerprint [0-9a-f]\{16\}$' || { echo "NOT THE EXPECTED LINE"; verdict=1; }
  echo "=== 2. over TLS, for a name the certificate does not carry ==="
  L2=$("$W/harb" get 127.0.0.1 18443 /health --tls --ca "$W/root.crt" --name other.local); echo "$L2"
  echo "$L2" | grep -q -- 'the handshake with 127.0.0.1 failed' || { echo "NOT REFUSED"; verdict=1; }
  echo "=== 3. plain HTTP on the TLS port ==="
  L3=$("$W/harb" get 127.0.0.1 18443 /health); echo "$L3"
  echo "$L3" | grep -q -- '-- 400' || { echo "NOT A 400"; verdict=1; }
  kill $CPID 2>/dev/null; wait $CPID 2>/dev/null
  cp "$W/caddy.log" zig-out/wsl/front_outside_caddy.log 2>/dev/null
  echo "=== what caddy kept of its own ==="
  ls "$W/storage/pki/authorities/local" 2>/dev/null | sed 's/^/  /'
  grep -c '"level":"info"' "$W/caddy.log" 2>/dev/null | sed 's/^/  info lines in caddy.log: /'
  echo "=== verdict ==="
  if [ "$verdict" -eq 0 ]; then echo "PROVEN OUTSIDE: Caddy as an unprivileged user ends TLS under a root it was given, and harb get trusts that root and nothing else"; else echo "NOT PROVEN"; fi
  echo "exit $verdict"
  exit "$verdict"
) 2>&1 | tee "$LOG"
exit "${PIPESTATUS[0]}"
